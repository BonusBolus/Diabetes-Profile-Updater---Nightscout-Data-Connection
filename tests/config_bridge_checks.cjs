const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert');
const html=fs.readFileSync(path.join(__dirname,'../graph_component/index.html'),'utf8');
const frame={contentWindow:{}};const sent=[],handlers={};
const parent={postMessage:m=>sent.push(m)};
const context={window:{parent,addEventListener:(key,f)=>handlers[key]=f},document:{getElementById:()=>frame,body:{style:{}}}};
vm.runInNewContext(html.split('<script>')[1].split('</script>')[0],context);
assert.equal(sent[0].type,'streamlit:componentReady');assert.equal(sent[0].apiVersion,1);
handlers.message({source:parent,data:{type:'streamlit:render',args:{height:860,html:'<h1>Viewer</h1>'}}});
assert.equal(frame.srcdoc,'<h1>Viewer</h1>');assert.equal(sent.at(-1).height,860);
const request={id:'1',name:'Sleep',config:{layers:['Garmin · Sleep']}};
const count=sent.length;
handlers.message({source:{},data:{type:'profile-studio:save',request}});assert.equal(sent.length,count);
handlers.message({source:frame.contentWindow,data:{type:'profile-studio:save',request}});
assert.equal(sent.at(-1).type,'streamlit:setComponentValue');assert.equal(sent.at(-1).dataType,'json');
assert.deepEqual(sent.at(-1).value,request);
handlers.message({source:frame.contentWindow,data:{type:'profile-studio:report',request:{id:'2',kind:'report'}}});
assert.equal(sent.at(-1).value.kind,'report');
